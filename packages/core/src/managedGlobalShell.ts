import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import type { openGlobalPathGuard, GlobalGuardTree, GlobalGuardTreeRow } from './managedGlobalGuard.js';
import type { createGlobalMutationJournal } from './managedGlobalJournal.js';
import { writeGlobalPrivateEvidence, type prepareGlobalObjectPreservation } from './managedGlobalPreservation.js';
import type { snapshotGlobalPackage } from './managedGlobalSnapshot.js';
import { renderManagedShellWrappers, type ManagedShellPlan } from './managedShell.js';
import type { ManagedNodeProof } from './managedNode.js';

type Guard = Awaited<ReturnType<typeof openGlobalPathGuard>>;
type Journal = ReturnType<typeof createGlobalMutationJournal>;
type Engine = ReturnType<typeof prepareGlobalObjectPreservation>;
type ObjectState = { name: string; backupName: string; status: 'absent' | 'installed' | 'quarantined' | 'unknown'; rows: GlobalGuardTreeRow[] | null };
const sha = (value: unknown) => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const requireOutcome = (result: { status: string }, status: string) => { if (result.status !== status) throw Object.assign(Error('global_shell_' + status + '_unconfirmed'), { operationResult: result }); };
const errorSha = (error: unknown) => sha(error instanceof Error ? error.name + ':' + error.message : String(error));

/** Product-owned publication. Nothing here accepts host scripts, generated bytes or a collector override. */
export function prepareGlobalShellInstallation(guard: Guard, journal: Journal, engine: Engine, runDirectory: string, root: string, plan: ManagedShellPlan, verify: () => Promise<void>, node: ReturnType<typeof snapshotGlobalPackage>['node'], nodeProof: ManagedNodeProof) {
  node = structuredClone(node); assert.equal(node.canonical, plan.registrationNode, 'global_shell_node_binding_invalid');
  nodeProof = structuredClone(nodeProof);
  assert.ok(nodeProof.executable.canonical === node.canonical && nodeProof.executable.alias === node.alias && nodeProof.capability.version === node.version
    && nodeProof.executable.identity.contentSha256 === node.binary[0]?.sha256, 'global_shell_node_proof_changed');
  const initial = journal.read(), generated = renderManagedShellWrappers(plan.registrationNode, plan.launcher, plan.windows);
  assert.deepEqual(plan.files.map(({ name, content, sha256 }) => ({ name, content, sha256 })), generated, 'global_shell_invalid_plan');
  const files: ObjectState[] = generated.map((file, index) => ({ name: file.name, backupName: 'generated-' + index, status: 'absent', rows: null }));
  const manifest: ObjectState = { name: 'shell', backupName: 'generated-shell', status: 'absent', rows: null };
  const held = new Map<string, GlobalGuardTree>(); let attempted = false, uncertain = false;
  const snapshot = () => ({ schema: 'caveat.global_shell_objects.v1' as const, files: structuredClone(files), manifest: structuredClone(manifest) });
  const verifyOwned = () => {
    assert.ok(!uncertain, 'global_shell_uncertain');
    for (const row of [...files, manifest]) if (row.status === 'installed' || row.status === 'quarantined') {
      assert.deepEqual(guard.readTree(held.get(row.name)!), row.rows, 'global_shell_owned_object_changed');
    }
  };
  const record = (step: string, operation: 'wrapper' | 'manifest', outcome: 'confirmed' | 'unknown', result: unknown, errorSha256?: string) => {
    const evidence = writeGlobalPrivateEvidence(guard, runDirectory, 'state-' + initial.header.runId + '-' + journal.read().nextSequence + '.json', {
      schema: 'caveat.global_shell_operation.v1', planSha256: initial.header.planSha256, runId: initial.header.runId,
      step, operation, manifest: engine.manifest(), shell: snapshot(), result, errorSha256,
    });
    journal.result(step, operation, outcome, evidence.sha256);
  };
  const perform = async (row: ObjectState, operation: 'wrapper' | 'manifest', restore: boolean, mutate: () => unknown) => {
    assert.ok(!uncertain && journal.read().status === 'ready', 'global_shell_uncertain_or_interrupted');
    try { await verify(); verifyOwned(); }
    catch (error) { return { status: 'stopped' as const, errorSha256: errorSha(error), shell: snapshot() }; }
    const step = (restore ? 'retire.generated.' : 'publish.generated.') + row.name;
    journal.intent(step, operation, sha(snapshot()));
    let result: unknown, errorSha256: string | undefined;
    try { result = mutate(); verifyOwned(); }
    catch (error) {
      uncertain = true; row.status = 'unknown'; errorSha256 = errorSha(error);
      const observe = (directory: string, name: string) => { try { const identity = guard.observe(directory, name); return identity ? { state: 'present', identity } : { state: 'absent' }; } catch { return { state: 'unknown' }; } };
      result = { operationResult: (error as { operationResult?: unknown })?.operationResult ?? result,
        observations: { destination: observe(row === manifest ? root : plan.binDir, row.name),
          stage: observe(runDirectory, row === manifest ? 'new-shell' : row.backupName), quarantine: observe(runDirectory, 'used-' + row.backupName) } };
    }
    const outcome = uncertain ? 'unknown' : 'confirmed';
    try { record(step, operation, outcome, result, errorSha256); }
    catch (error) { uncertain = true; return { status: 'unknown' as const, resultRecorded: false, errorSha256: errorSha(error), shell: snapshot() }; }
    if (outcome === 'confirmed') {
      try { await verify(); verifyOwned(); }
      catch (error) { uncertain = true; return { status: 'stopped' as const, errorSha256: errorSha(error), shell: snapshot(), recovery: 'fresh-known-only-plan-required' as const }; }
    }
    return { status: outcome, shell: snapshot() };
  };
  return {
    snapshot, verifyOwned,
    ownsLeaf(name: string) { return files.some(row => row.name === name && row.status === 'installed'); },
    ownsManifest() { return manifest.status === 'installed'; },
    async install() {
      assert.ok(!attempted, 'global_shell_install_already_attempted'); attempted = true;
      assert.ok(engine.manifest().objects.filter(row => row.role !== 'npm-management').every(row => row.state === 'preserved' && row.working?.status === 'absent'), 'global_shell_known_absent_required');
      for (const row of files) assert.equal(guard.observe(plan.binDir, row.name), null, 'global_shell_destination_exists');
      assert.equal(guard.observe(root, 'shell'), null, 'global_shell_manifest_destination_exists');
      for (const [index, row] of files.entries()) {
        const result = await perform(row, 'wrapper', false, () => {
          assert.equal(guard.observe(plan.binDir, row.name), null, 'global_shell_destination_exists');
          const token = guard.createJournal(runDirectory, row.backupName, Buffer.from(generated[index]!.content));
          const sealed = guard.sealJournalFile(token, true); requireOutcome(sealed, 'sealed');
          const moved = guard.moveTreeNoReplace(sealed.tree!, plan.binDir, row.name); requireOutcome(moved, 'moved');
          held.set(row.name, sealed.tree!); row.rows = guard.readTree(sealed.tree!); row.status = 'installed'; return { sealed, moved };
        });
        if (result.status !== 'confirmed') return result;
      }
      const result = await perform(manifest, 'manifest', false, () => {
        const directory = guard.createPrivateDirectory(runDirectory, 'new-shell');
        const value = { schema: 'caveat.managed_shell.v2', node: { canonical: node.canonical, version: node.version, binary: node.binary, proof: nodeProof }, registrationNode: plan.registrationNode, launcher: plan.launcher,
          entrySha256: plan.entrySha256, runtimeSha256: plan.runtimeSha256, binDir: plan.binDir, windows: plan.windows,
          binIdentity: guard.directoryIdentity(plan.binDir), files: files.map(row => ({ name: row.name, identity: row.rows![0]!.identity })) };
        const token = guard.createJournal(directory, 'manifest.json', Buffer.from(JSON.stringify(value) + '\n'));
        const file = guard.sealJournalFile(token, false); requireOutcome(file, 'sealed');
        guard.releaseWorkingTree(file.tree!);
        const sealed = guard.sealPrivateDirectory(directory); requireOutcome(sealed, 'sealed');
        const moved = guard.moveTreeNoReplace(sealed.tree!, root, 'shell'); requireOutcome(moved, 'moved');
        held.set(manifest.name, sealed.tree!); manifest.rows = guard.readTree(sealed.tree!); manifest.status = 'installed'; return { sealed, moved };
      });
      return result.status === 'confirmed' ? { status: 'installed' as const, shell: snapshot() } : result;
    },
    async quarantineKnown() {
      assert.ok(!uncertain && journal.read().status === 'ready', 'global_shell_uncertain_or_interrupted');
      for (const row of [manifest, ...files]) if (row.status === 'installed') {
        const result = await perform(row, row === manifest ? 'manifest' : 'wrapper', true, () => {
          const token = held.get(row.name)!, moved = guard.moveTreeNoReplace(token, runDirectory, 'used-' + row.backupName);
          requireOutcome(moved, 'moved'); row.rows = guard.readTree(token); row.status = 'quarantined'; return moved;
        });
        if (result.status !== 'confirmed') return result;
      }
      return { status: 'quarantined' as const, shell: snapshot() };
    },
    status() {
      if (uncertain) return { status: 'unknown' as const, shell: snapshot() };
      verifyOwned();
      return { status: files.every(row => row.status === 'installed') && manifest.status === 'installed' ? 'ready' as const : uncertain ? 'unknown' as const : 'partial' as const, shell: snapshot() };
    },
  };
}
